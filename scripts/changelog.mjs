#!/usr/bin/env node
// Build / InBul bookkeeping. See MD/README.md section 2 and 3.
//
//   node scripts/changelog.mjs --next-internal
//   node scripts/changelog.mjs --pending "<title>" "<summary>" --why "..." --verified "..." --next "..."
//   node scripts/changelog.mjs --tag
//   node scripts/changelog.mjs --changelog      (regenerate CHANGELOG.md only)
//
// Builds start at 1000. The git tag build-N is the source of truth for a number.
// InBul commits start their title with "InBulNN:" and get a tag InBulNN only.

import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FIRST_BUILD = 1000;
const BUILDS_DIR = join('MD', 'builds');
const CHANGELOG = 'CHANGELOG.md';
const FILES_MARK = '<!-- files:start (rebuilt from git, do not edit below) -->';

const git = (...args) => execFileSync('git', args, { encoding: 'utf8' }).trim();

function tags(pattern) {
  const re = new RegExp(`^${pattern}(\\d+)$`);
  return git('tag', '--list')
    .split('\n')
    .map((t) => re.exec(t))
    .filter(Boolean)
    .map((m) => Number(m[1]));
}

const lastBuildTag = () => Math.max(FIRST_BUILD - 1, ...tags('build-'));
const nextInternal = () => Math.max(0, ...tags('InBul')) + 1;

function buildFiles() {
  if (!existsSync(BUILDS_DIR)) return [];
  return readdirSync(BUILDS_DIR)
    .map((f) => /^build-(\d+)\.md$/.exec(f))
    .filter(Boolean)
    .map((m) => Number(m[1]))
    .sort((a, b) => a - b);
}

function flag(args, name) {
  const i = args.indexOf(name);
  return i === -1 ? '' : args[i + 1] ?? '';
}

function filesChanged() {
  const out = git('diff', '--cached', '--name-status', '--', '.', ':!MD/builds', ':!CHANGELOG.md');
  if (!out) return '_No staged changes. `git add` the change files before running this._';
  return out
    .split('\n')
    .map((l) => {
      const [status, ...p] = l.split('\t');
      return `- \`${status}\` ${p.join(' → ')}`;
    })
    .join('\n');
}

function writeReport(n, title, summary, why, verified, next) {
  mkdirSync(BUILDS_DIR, { recursive: true });
  const file = join(BUILDS_DIR, `build-${n}.md`);
  let head;
  if (existsSync(file)) {
    // The hand-written part is written once and never overwritten.
    head = readFileSync(file, 'utf8').split(FILES_MARK)[0].trimEnd();
  } else {
    const date = new Date().toISOString().slice(0, 10);
    head = [
      `# Build ${n}: ${title}`,
      '',
      `Date: ${date}`,
      '',
      '## What changed',
      summary || '_TODO_',
      '',
      '## Why',
      why || '_TODO_',
      '',
      '## How it was verified',
      verified || '_TODO_',
      '',
      '## What to improve next',
      next || '_TODO_',
    ].join('\n');
  }
  writeFileSync(file, `${head}\n\n${FILES_MARK}\n## Files changed\n${filesChanged()}\n`);
  return file;
}

function regenerateChangelog() {
  const entries = buildFiles()
    .reverse()
    .map((n) => {
      const text = readFileSync(join(BUILDS_DIR, `build-${n}.md`), 'utf8');
      const title = /^# Build \d+: (.*)$/m.exec(text)?.[1] ?? '';
      const date = /^Date: (.*)$/m.exec(text)?.[1] ?? '';
      const what = /## What changed\n([\s\S]*?)\n\n## /.exec(text)?.[1]?.trim() ?? '';
      return `## Build ${n}: ${title}\n${date}\n\n${what}\n\nReport: [build-${n}.md](MD/builds/build-${n}.md)`;
    });
  const body = entries.length ? entries.join('\n\n') : '_No builds yet. The first one will be Build 1000._';
  writeFileSync(
    CHANGELOG,
    `# Changelog\n\nGenerated by \`scripts/changelog.mjs\`. Never edit by hand.\n\n${body}\n`,
  );
}

const args = process.argv.slice(2);

if (args.includes('--next-internal')) {
  console.log(`InBul${nextInternal()}`);
} else if (args[0] === '--pending') {
  const [, title, summary] = args;
  if (!title) {
    console.error('usage: --pending "<title>" "<summary>" [--why ..] [--verified ..] [--next ..]');
    process.exit(1);
  }
  // A report that exists but is not tagged yet is the pending build; reuse its number.
  const unTagged = buildFiles().filter((b) => b > lastBuildTag());
  const n = unTagged.length ? unTagged[0] : lastBuildTag() + 1;
  const file = writeReport(n, title, summary, flag(args, '--why'), flag(args, '--verified'), flag(args, '--next'));
  regenerateChangelog();
  console.log(`Build ${n} report: ${file}\nNext: git add MD/builds CHANGELOG.md, commit, then --tag`);
} else if (args.includes('--changelog')) {
  regenerateChangelog();
  console.log(`Wrote ${CHANGELOG}`);
} else if (args.includes('--tag')) {
  const subject = git('log', '-1', '--pretty=%s');
  const internal = /^(InBul\d+):/.exec(subject);
  if (internal) {
    git('tag', internal[1]);
    console.log(`Tagged ${internal[1]}`);
  } else {
    const pending = buildFiles().filter((b) => b > lastBuildTag());
    if (!pending.length) {
      console.error('No pending build report and the commit is not an InBul. Nothing to tag.');
      process.exit(1);
    }
    git('tag', `build-${pending[0]}`);
    console.log(`Tagged build-${pending[0]}`);
  }
} else {
  console.error('usage: --next-internal | --changelog | --pending "<title>" "<summary>" | --tag');
  process.exit(1);
}
